<?php
declare(strict_types=1);

// Installed from modules/admin (v1). To update: re-run the installer.
//
// A small, single-owner admin area. One password, no user table, no roles —
// anything larger belongs in an application, not in a markdown website.
//
// Design notes, because each is load-bearing:
//
//   * **The default site has no admin at all.** This module exists only
//     because some modules (a newsletter, say) genuinely need a screen. An
//     admin URL that does not exist is attack surface that does not exist,
//     so nothing here is in the core.
//   * **The password is only ever stored as a bcrypt hash**, generated by
//     scripts/admin-password.php. A plaintext password never appears in
//     .env, in the repo, or in a log.
//   * **Auth is checked before any page file is touched**, in the front
//     controller below — a page cannot forget to check.
//   * **Pages are discovered, not registered.** A module drops one file into
//     templates/admin/pages/ and it appears. There is no registry to edit
//     and therefore no registry two modules can conflict over.

require_once ROOT . '/lib/ratelimit.php';
require_once ROOT . '/lib/request.php';

const ADMIN_SESSION_KEY      = 'agentsite_admin';
const ADMIN_IDLE_TIMEOUT     = 3600;    // 1 hour without a request
const ADMIN_ABSOLUTE_TIMEOUT = 43200;   // 12 hours, however active
const ADMIN_LOGIN_ATTEMPTS   = 5;       // per window, per IP
const ADMIN_LOGIN_WINDOW     = 900;     // 15 minutes
const ADMIN_RATE_SCOPE       = 'admin-login';
const ADMIN_LOG_DIR          = ROOT . '/_logs/admin';

/** The configured admin base path, always with a leading and trailing slash. */
function admin_base_path(): string
{
    $path = getenv('ADMIN_PATH') ?: '/admin';
    return '/' . trim($path, '/') . '/';
}

/**
 * Stealth mode: when on, an unauthenticated visitor gets the site's ordinary
 * 404 instead of a login form, so the admin area is not discoverable by
 * probing. The owner still reaches it because they know the path.
 */
function admin_is_stealth(): bool
{
    $value = getenv('ADMIN_STEALTH');
    return is_string($value) && in_array(strtolower($value), ['1', 'true', 'yes'], true);
}

/**
 * The stored bcrypt hash, from config/admin-password.hash.
 *
 * **A file, not an environment variable, and the reason is specific.** A
 * bcrypt hash contains `$` characters, and Docker Compose interpolates `$`
 * sequences in .env — so a hash pasted there arrives at the application with
 * a chunk silently eaten, and the only symptom is that the correct password
 * stops working. A file is read by PHP alone and cannot be mangled by
 * anything in between.
 *
 * ADMIN_PASSWORD_HASH is still honoured for platforms where a secret can
 * only be delivered as an environment variable, but if you use it there, any
 * `$` must be written `$$` in a compose-interpolated context.
 */
function admin_password_hash(): string
{
    $file = ROOT . '/config/admin-password.hash';
    if (is_file($file)) {
        $hash = trim((string) file_get_contents($file));
        if ($hash !== '') {
            return $hash;
        }
    }
    $env = getenv('ADMIN_PASSWORD_HASH');
    return is_string($env) ? trim($env) : '';
}

/** Start the admin session with hardened cookie parameters. */
function admin_session_start(): void
{
    if (session_status() === PHP_SESSION_ACTIVE) {
        return;
    }
    session_set_cookie_params([
        'lifetime' => 0,
        'path'     => admin_base_path(),
        'httponly' => true,
        'samesite' => 'Strict',
        // Secure only when the request actually arrived over TLS — set
        // unconditionally, a developer on plain http://localhost could never
        // log in.
        'secure'   => request_is_https(),
    ]);
    session_name('agentsite_admin_sid');
    session_start();
}

/** Whether the current request carries a valid, unexpired admin session. */
function admin_is_authenticated(): bool
{
    admin_session_start();
    $session = $_SESSION[ADMIN_SESSION_KEY] ?? null;
    if (!is_array($session) || ($session['ok'] ?? false) !== true) {
        return false;
    }
    $now = time();
    if (($now - (int) ($session['seen'] ?? 0)) > ADMIN_IDLE_TIMEOUT) {
        admin_logout();
        return false;
    }
    if (($now - (int) ($session['start'] ?? 0)) > ADMIN_ABSOLUTE_TIMEOUT) {
        admin_logout();
        return false;
    }
    $_SESSION[ADMIN_SESSION_KEY]['seen'] = $now;
    return true;
}

/**
 * Attempt a login. Returns 'ok', 'bad' (wrong password) or 'throttled'.
 * Rate limiting uses the core primitive, so the form module and this one
 * share a single implementation of "N attempts per window".
 */
function admin_attempt_login(string $password): string
{
    $ip    = client_ip();
    $limit = ratelimit_check(ADMIN_RATE_SCOPE, $ip, ADMIN_LOGIN_ATTEMPTS, ADMIN_LOGIN_WINDOW);
    if (!$limit['allowed']) {
        admin_log('login throttled', $ip);
        return 'throttled';
    }

    $hash = admin_password_hash();
    if ($hash === '' || !password_verify($password, $hash)) {
        admin_log('login failed', $ip);
        return 'bad';
    }

    admin_session_start();
    // Regenerate on privilege change — otherwise a session id an attacker
    // planted before login would become an authenticated one.
    session_regenerate_id(true);
    $now = time();
    $_SESSION[ADMIN_SESSION_KEY] = ['ok' => true, 'start' => $now, 'seen' => $now];
    ratelimit_reset(ADMIN_RATE_SCOPE, $ip);
    admin_log('login ok', $ip);
    return 'ok';
}

function admin_logout(): void
{
    admin_session_start();
    unset($_SESSION[ADMIN_SESSION_KEY]);
    session_destroy();
}

/** A CSRF token for the current session, created on first use. */
function admin_csrf_token(): string
{
    admin_session_start();
    if (!isset($_SESSION['admin_csrf']) || !is_string($_SESSION['admin_csrf'])) {
        $_SESSION['admin_csrf'] = bin2hex(random_bytes(32));
    }
    return $_SESSION['admin_csrf'];
}

/** Verify a submitted CSRF token. Every admin POST must call this. */
function admin_csrf_valid(?string $submitted): bool
{
    admin_session_start();
    $expected = $_SESSION['admin_csrf'] ?? '';
    return is_string($expected) && $expected !== ''
        && is_string($submitted) && hash_equals($expected, $submitted);
}

/**
 * Admin pages, discovered from templates/admin/pages/*.php. Each page file
 * may return an array describing itself (['title_key' => …, 'order' => …])
 * when included with $admin_describe = true.
 *
 * @return array<string, array{slug:string,title_key:string,order:int,file:string}>
 */
function admin_pages(): array
{
    $pages = [];
    foreach (glob(ROOT . '/templates/admin/pages/*.php') ?: [] as $file) {
        $slug = basename($file, '.php');
        if (!preg_match('/^[a-z0-9-]+$/', $slug)) {
            continue;   // a page whose name is not routable is not a page
        }
        $admin_describe = true;
        $described = include $file;
        $pages[$slug] = [
            'slug'      => $slug,
            'title_key' => is_array($described) ? (string) ($described['title_key'] ?? $slug) : $slug,
            'order'     => is_array($described) ? (int) ($described['order'] ?? 50) : 50,
            'file'      => $file,
        ];
    }
    uasort($pages, fn(array $a, array $b) => [$a['order'], $a['slug']] <=> [$b['order'], $b['slug']]);
    return $pages;
}

/** URL path for an admin page (or the dashboard when $slug is ''). */
function admin_url(string $slug = ''): string
{
    return admin_base_path() . ($slug === '' ? '' : $slug . '/');
}

/** Append a line to the admin audit log. Never logs the password. */
function admin_log(string $event, string $ip): void
{
    if (!is_dir(ADMIN_LOG_DIR) && !mkdir(ADMIN_LOG_DIR, 0775, true) && !is_dir(ADMIN_LOG_DIR)) {
        return;
    }
    $line = date('c') . "\t" . $ip . "\t" . $event . "\t" . request_header('HTTP_USER_AGENT') . "\n";
    file_put_contents(ADMIN_LOG_DIR . '/access.log', $line, FILE_APPEND | LOCK_EX);
}

/**
 * Headers every admin response carries. `no-store` keeps admin pages out of
 * browser and proxy caches; `noindex` keeps them out of search engines.
 *
 * There is deliberately NO `Disallow: /admin/` in robots.txt — a Disallow
 * line publishes the path to anyone who reads robots.txt, which is precisely
 * everyone you did not want finding it.
 */
function admin_send_headers(): void
{
    header('Cache-Control: no-store, no-cache, must-revalidate, private');
    header('Pragma: no-cache');
    header('X-Robots-Tag: noindex, nofollow');
}
